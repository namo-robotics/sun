/** Generate a readable shell script exposing installed binary directories. */
#include "driver/env_script.h"

#include <filesystem>
#include <fstream>
#include <set>

#include "driver/build_graph.h"
#include "support/error.h"

/** Generates shell environments for configured build products. */
namespace sun::driver {
/** Keeps shell quoting private to the environment generator. */
namespace {
/** Quote a literal shell word, including paths containing apostrophes. */
std::string quoteShellPath(const std::filesystem::path& path) {
  std::string result = "'";
  for (const char c : path.string()) {
    if (c == '\'') {
      result += "'\\''";
    } else {
      result += c;
    }
  }
  return result + "'";
}

}  // namespace

void writeEnvScript(const ConfigGraph& graph, const std::string& targetTriple) {
  /** Shortens filesystem operations used to locate installed binaries. */
  namespace fs = std::filesystem;
  std::set<fs::path> directories;
  for (const auto& file : graph.projects) {
    const auto config =
        configureBuildPaths(graph, SunConfig::loadFile(file, targetTriple));
    const auto bin = fs::path(config.pathVariables.at("SUN_INSTALL")) / "bin";
    if (fs::is_directory(bin)) {
      directories.insert(fs::absolute(bin));
    }
  }
  const auto path = graph.root / ".sun/install/env.sh";
  fs::create_directories(path.parent_path());
  std::ofstream output(path);
  output << "# Generated by sun build. Source this file to use installed "
            "binaries.\n";
  for (const auto& bin : directories) {
    output << "export PATH=" << quoteShellPath(bin) << "${PATH:+:\"$PATH\"}\n";
  }
  output.close();
  if (!output) {
    sun::support::logAndThrowError("cannot write build environment: " +
                                  path.string());
  }
}

}  // namespace sun::driver
